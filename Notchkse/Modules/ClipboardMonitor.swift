import AppKit
import Observation
import SwiftUI

struct ClipItem: Identifiable, Equatable {
    enum Kind: Equatable {
        case text(String)
        case image(file: URL, type: NSPasteboard.PasteboardType)
        case files([URL])
    }

    let id = UUID()
    let kind: Kind
    let date = Date()
    var preview: NSImage?
    var appIcon: NSImage?

    var text: String? { if case .text(let t) = kind { t } else { nil } }
}

/// O macOS não avisa quando o clipboard muda, então lemos apenas o
/// `changeCount` (um inteiro) a cada 0,6 s — custo praticamente zero.
@Observable
final class ClipboardMonitor {
    static let limit = 10

    private(set) var items: [ClipItem] = []

    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastChange = NSPasteboard.general.changeCount
    @ObservationIgnored private let storage: URL = {
        let dir = FileManager.default.urls(for: .cachesDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("Notchkse/Clipboard", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir
    }()

    /// Tipos que gerenciadores de senha usam para pedir "não guarde isso".
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ]

    func start() {
        guard timer == nil else { return }
        lastChange = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.6, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        timer.tolerance = 0.3
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        clear()
    }

    func clear() {
        items.removeAll()
        try? FileManager.default.removeItem(at: storage)
        try? FileManager.default.createDirectory(at: storage, withIntermediateDirectories: true)
    }

    func copy(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.kind {
        case .text(let text): pb.setString(text, forType: .string)
        case .files(let urls): pb.writeObjects(urls as [NSURL])
        case .image(let file, let type):
            if let data = try? Data(contentsOf: file) { pb.setData(data, forType: type) }
        }
        lastChange = pb.changeCount
        if let index = items.firstIndex(of: item) {
            items.move(fromOffsets: IndexSet(integer: index), toOffset: 0)
        }
    }

    func remove(_ item: ClipItem) {
        if case .image(let file, _) = item.kind { try? FileManager.default.removeItem(at: file) }
        items.removeAll { $0.id == item.id }
    }

    private func check() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        let types = pb.types ?? []
        if types.contains(where: { Self.ignoredTypes.contains($0.rawValue) }) { return }

        let icon = NSWorkspace.shared.frontmostApplication?.icon
        var item: ClipItem?

        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            item = ClipItem(kind: .files(urls), preview: NSWorkspace.shared.icon(forFile: urls[0].path))
        } else if let text = pb.string(forType: .string),
                  !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let capped = String(text.prefix(20_000))
            if let existing = items.first(where: { $0.text == capped }) {
                items.removeAll { $0.id == existing.id }
            }
            item = ClipItem(kind: .text(capped))
        } else if let type = [NSPasteboard.PasteboardType.png, .tiff].first(where: types.contains),
                  let data = pb.data(forType: type) {
            // Imagem completa vai para o disco; na memória fica só a miniatura.
            let file = storage.appendingPathComponent(UUID().uuidString)
            try? data.write(to: file)
            item = ClipItem(kind: .image(file: file, type: type),
                            preview: ImageUtils.thumbnail(data: data, maxPixel: 240))
        }

        guard var item else { return }
        item.appIcon = icon
        items.insert(item, at: 0)
        while items.count > Self.limit { remove(items[items.count - 1]) }
    }
}
